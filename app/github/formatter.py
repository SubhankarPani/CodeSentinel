from app.models.review import ReviewResult


def format_review_as_markdown(review: ReviewResult) -> str:
    """Convert a CodeSentinel review into GitHub Markdown."""

    lines = []

    lines.append("## 🤖 CodeSentinel Review")
    lines.append("")

    if not review.issues:
        lines.append("✅ **No significant issues found.**")
        lines.append("")
        lines.append("_Generated by CodeSentinel_")

        return "\n".join(lines)

    lines.append(
        f"CodeSentinel found **{len(review.issues)} issue(s)**."
    )
    lines.append("")

    for index, issue in enumerate(review.issues, start=1):

        lines.append(
            f"### {index}. {issue.severity} — {issue.category}"
        )
        lines.append("")

        if issue.file:
            lines.append(f"**File:** `{issue.file}`")

        if issue.line:
            lines.append(f"**Line:** `{issue.line}`")

        lines.append("")
        lines.append("**Description**")
        lines.append("")
        lines.append(issue.description)
        lines.append("")

        lines.append("**Recommendation**")
        lines.append("")
        lines.append(issue.recommendation)
        lines.append("")

        lines.append("---")
        lines.append("")

    lines.append("_Generated by CodeSentinel_")

    return "\n".join(lines)