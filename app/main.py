from fastapi import FastAPI, HTTPException
from pydantic import BaseModel

from app.config import TEST_MODE
from app.github.client import GitHubClient
from app.github.formatter import format_review_as_markdown
from app.models.review import ReviewFinding, ReviewResult
from app.services.review_service import ReviewService


app = FastAPI(
    title="CodeSentinel",
    description="Autonomous AI-powered GitHub Pull Request Code Review",
    version="1.0.0"
)


class ReviewRequest(BaseModel):
    repository: str
    pull_number: int


def create_test_review() -> ReviewResult:
    """Create a fake review for testing without Gemini."""

    return ReviewResult(
        issues=[
            ReviewFinding(
                severity="LOW",
                category="Code Quality",
                file="test_code.py",
                line="2",
                description=(
                    "Test finding generated by CodeSentinel "
                    "TEST_MODE."
                ),
                recommendation=(
                    "This is a test recommendation. "
                    "No Gemini API call was made."
                )
            )
        ]
    )


@app.get("/")
def root():
    return {
        "message": "CodeSentinel API is running"
    }


@app.get("/health")
def health():
    return {
        "status": "healthy"
    }


@app.post("/review")
def review_pull_request(request: ReviewRequest):

    try:

        github_client = GitHubClient()

        print(
            f"Fetching PR #{request.pull_number} "
            f"from {request.repository}..."
        )

        # --------------------------------------------------
        # GET PULL REQUEST FILES
        # --------------------------------------------------

        files = list(
            github_client.get_pull_request_files(
                request.repository,
                request.pull_number
            )
        )

        if not files:

            raise HTTPException(
                status_code=400,
                detail="No changed files found in the Pull Request."
            )

        print(
            f"Files changed: {len(files)}"
        )

        # --------------------------------------------------
        # BUILD CODE DIFF
        # --------------------------------------------------

        code_diff = ""

        for file in files:

            code_diff += (
                f"\n\nFile: {file.filename}\n"
            )

            code_diff += (
                f"Status: {file.status}\n"
            )

            code_diff += (
                f"Additions: {file.additions}\n"
            )

            code_diff += (
                f"Deletions: {file.deletions}\n"
            )

            code_diff += "\n--- Diff ---\n"

            code_diff += (
                file.patch or "No patch available."
            )

        # --------------------------------------------------
        # REVIEW
        # --------------------------------------------------

        print("\nStarting CodeSentinel review...")

        if TEST_MODE:

            print("⚠️ TEST_MODE enabled.")
            print("Skipping Gemini agents.")

            final_review = create_test_review()

        else:

            print("🤖 Running Gemini agents...")

            review_service = ReviewService()

            reviews = review_service.review(
                code_diff
            )

            if "final" not in reviews:

                raise HTTPException(
                    status_code=500,
                    detail=(
                        "CodeSentinel could not "
                        "generate a final review."
                    )
                )

            final_review = reviews["final"]

        # --------------------------------------------------
        # FORMAT REVIEW
        # --------------------------------------------------

        github_comment = format_review_as_markdown(
            final_review
        )

        # --------------------------------------------------
        # POST GITHUB COMMENT
        # --------------------------------------------------

        print("\nPosting review to GitHub...")

        comment = github_client.post_pull_request_comment(
            request.repository,
            request.pull_number,
            github_comment
        )

        print("✅ Review posted successfully!")

        return {
            "status": "success",
            "repository": request.repository,
            "pull_number": request.pull_number,
            "issues_found": len(final_review.issues),
            "comment_url": comment.html_url,
            "review": final_review.model_dump()
        }

    except HTTPException:
        raise

    except Exception as error:

        print(
            f"\n❌ CodeSentinel error: {error}"
        )

        raise HTTPException(
            status_code=500,
            detail=str(error)
        )