from app.config import TEST_MODE
from app.agents.style_agent import StyleAgent
from app.agents.logic_agent import LogicAgent
from app.agents.security_agent import SecurityAgent
from app.agents.review_agent import ReviewAgent
from app.models.review import ReviewFinding, ReviewResult


class ReviewService:
    """Coordinates all CodeSentinel review agents."""

    def __init__(self, progress_callback=None):
        self.style_agent = StyleAgent()
        self.logic_agent = LogicAgent()
        self.security_agent = SecurityAgent()
        self.review_agent = ReviewAgent()

        self.progress_callback = progress_callback

    def update_progress(self, status):
        """Send current agent status to the caller."""

        if self.progress_callback:
            self.progress_callback(status)

    def create_test_review(self) -> ReviewResult:
        return ReviewResult(
            issues=[
                ReviewFinding(
                    severity="LOW",
                    category="Code Quality",
                    file="test_code.py",
                    line="2",
                    description="Test finding generated by CodeSentinel TEST_MODE.",
                    recommendation="This is a test recommendation. No Gemini API call was made."
                )
            ]
        )

    def review(self, code_diff: str) -> dict:
        """Run all agents and return individual + final reviews."""

        try:

            # --------------------------------
            # TEST MODE
            # --------------------------------

            if TEST_MODE:

                print("\n⚠️ TEST_MODE enabled.")
                print("Skipping Gemini agents.")

                empty_review = ReviewResult(issues=[])

                final_review = self.create_test_review()

                return {
                    "style": empty_review,
                    "logic": empty_review,
                    "security": empty_review,
                    "final": final_review
                }


            # --------------------------------
            # STYLE AGENT
            # --------------------------------

            self.update_progress("style_running")

            print("\nRunning Style Agent...")

            style_review = self.style_agent.review(code_diff)

            self.update_progress("style_completed")


            # --------------------------------
            # LOGIC AGENT
            # --------------------------------

            self.update_progress("logic_running")

            print("Running Logic Agent...")

            logic_review = self.logic_agent.review(code_diff)

            self.update_progress("logic_completed")


            # --------------------------------
            # SECURITY AGENT
            # --------------------------------

            self.update_progress("security_running")

            print("Running Security Agent...")

            security_review = self.security_agent.review(code_diff)

            self.update_progress("security_completed")


            # --------------------------------
            # REVIEW AGENT
            # --------------------------------

            self.update_progress("review_running")

            print("Running Review Agent...")

            final_review = self.review_agent.review(
                style_review,
                logic_review,
                security_review
            )

            self.update_progress("review_completed")


            # --------------------------------
            # RETURN RESULTS
            # --------------------------------

            return {
                "style": style_review,
                "logic": logic_review,
                "security": security_review,
                "final": final_review
            }


        except Exception as error:

            error_message = str(error)

            print("\n" + "=" * 50)
            print("❌ CODESENTINEL REVIEW FAILED")
            print("=" * 50)

            if (
                "429" in error_message
                or "RESOURCE_EXHAUSTED" in error_message
                or "quota" in error_message.lower()
            ):
                print("\nReason: Gemini API quota exceeded.")
                print("Please wait for your quota to reset.")

            else:
                print(f"\nError: {error_message}")

            print("=" * 50)

            raise