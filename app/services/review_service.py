from app.agents.style_agent import StyleAgent
from app.agents.logic_agent import LogicAgent
from app.agents.security_agent import SecurityAgent
from app.agents.review_agent import ReviewAgent
from app.config import TEST_MODE
from app.models.review import ReviewFinding, ReviewResult


class ReviewService:
    """Coordinates the complete CodeSentinel review workflow."""

    def __init__(self):

        self.style_agent = StyleAgent()
        self.logic_agent = LogicAgent()
        self.security_agent = SecurityAgent()
        self.review_agent = ReviewAgent()

    def create_test_review(self) -> ReviewResult:
        """Create a fake review for testing without Gemini."""

        return ReviewResult(
            issues=[
                ReviewFinding(
                    severity="LOW",
                    category="Code Quality",
                    file="test_code.py",
                    line="2",
                    description=(
                        "Test finding generated by "
                        "CodeSentinel TEST_MODE."
                    ),
                    recommendation=(
                        "This is a test recommendation. "
                        "No Gemini API call was made."
                    )
                )
            ]
        )

    def review(self, code_diff: str) -> dict:
        """Run all CodeSentinel review agents."""

        # --------------------------------------------------
        # TEST MODE
        # --------------------------------------------------

        if TEST_MODE:

            print("\n⚠️ TEST_MODE enabled.")
            print("Skipping Gemini agents.")

            final_review = self.create_test_review()

            return {
                "style": None,
                "logic": None,
                "security": None,
                "final": final_review,
            }

        # --------------------------------------------------
        # REAL AI MODE
        # --------------------------------------------------

        try:

            print("\n🤖 Running Gemini agents...")

            print("\nRunning Style Agent...")
            style_review = self.style_agent.review(
                code_diff
            )

            print("Running Logic Agent...")
            logic_review = self.logic_agent.review(
                code_diff
            )

            print("Running Security Agent...")
            security_review = self.security_agent.review(
                code_diff
            )

            print("Running Review Agent...")
            final_review = self.review_agent.review(
                style_review,
                logic_review,
                security_review
            )

            return {
                "style": style_review,
                "logic": logic_review,
                "security": security_review,
                "final": final_review,
            }

        except Exception as error:

            error_message = str(error)

            print("\n" + "=" * 50)
            print("❌ CODESENTINEL REVIEW FAILED")
            print("=" * 50)

            if (
                "429" in error_message
                or "RESOURCE_EXHAUSTED" in error_message
                or "quota" in error_message.lower()
            ):

                print(
                    "\nReason: Gemini API quota/rate limit exceeded."
                )

                print(
                    "Please wait for the quota to reset "
                    "or try again later."
                )

            else:

                print(
                    f"\nError: {error_message}"
                )

            print("=" * 50)

            return {}