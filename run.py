from app.config import TEST_MODE, POST_TO_GITHUB
from app.github.client import GitHubClient
from app.github.formatter import format_review_as_markdown
from app.models.review import ReviewFinding, ReviewResult
from app.services.review_service import ReviewService


def create_test_review() -> ReviewResult:
    """Create a fake review for testing without calling Gemini."""

    return ReviewResult(
        issues=[
            ReviewFinding(
                severity="MEDIUM",
                category="Performance",
                file="src/requests/utils.py",
                line="149",
                description=(
                    "This is a test finding generated by "
                    "CodeSentinel TEST_MODE."
                ),
                recommendation=(
                    "This is a test recommendation. "
                    "No Gemini API call was made."
                )
            )
        ]
    )


def main():

    github_client = GitHubClient()

    repository_name = "SubhankarPani/CodeSentinel"
    pull_number = 1

    print("Fetching Pull Request...")

    files = list(
        github_client.get_pull_request_files(
            repository_name,
            pull_number
        )
    )

    print("Pull Request retrieved successfully!")
    print(f"Files changed: {len(files)}")

    # Combine all file diffs
    code_diff = ""

    for file in files:

        code_diff += f"\n\nFile: {file.filename}\n"
        code_diff += f"Status: {file.status}\n"
        code_diff += f"Additions: {file.additions}\n"
        code_diff += f"Deletions: {file.deletions}\n"
        code_diff += "\n--- Diff ---\n"
        code_diff += file.patch or "No patch available."

    print("\nStarting CodeSentinel review...")

    # --------------------------------------------------
    # TEST MODE
    # --------------------------------------------------

    if TEST_MODE:

        print("⚠️ TEST_MODE enabled.")
        print("Skipping Gemini agents.")

        final_review = create_test_review()

    # --------------------------------------------------
    # REAL AI MODE
    # --------------------------------------------------

    else:

        print("🤖 Running Gemini agents...")

        review_service = ReviewService()

        reviews = review_service.review(code_diff)

        if "final" not in reviews:

            print("\n===============================================")
            print("❌ CODESENTINEL REVIEW FAILED")
            print("===============================================")

            print("\nCodeSentinel could not generate the final review.")
            print("Please check the AI API status or quota.")

            return

        final_review = reviews["final"]

    # --------------------------------------------------
    # DISPLAY FINAL REVIEW
    # --------------------------------------------------

    print("\n================================")
    print("       CODESENTINEL REVIEW")
    print("================================")

    if not final_review.issues:

        print("\nNo significant issues found.")

    else:

        print(
            f"\nFound {len(final_review.issues)} issue(s)."
        )

        for index, issue in enumerate(
            final_review.issues,
            start=1
        ):

            print(f"\nIssue {index}")

            print(f"Severity: {issue.severity}")
            print(f"Category: {issue.category}")
            print(f"File: {issue.file}")
            print(f"Line: {issue.line}")

            print("\nDescription:")
            print(issue.description)

            print("\nRecommendation:")
            print(issue.recommendation)

            print("\n" + "-" * 50)

    # --------------------------------------------------
    # FORMAT REVIEW AS GITHUB MARKDOWN
    # --------------------------------------------------

    github_comment = format_review_as_markdown(
        final_review
    )

    # --------------------------------------------------
    # GITHUB COMMENT PREVIEW
    # --------------------------------------------------

    print("\n================================")
    print("       GITHUB COMMENT PREVIEW")
    print("================================")

    print(github_comment)

    # --------------------------------------------------
    # POST TO GITHUB
    # --------------------------------------------------

    if POST_TO_GITHUB:

        print("\nPosting review to GitHub...")

        comment = github_client.post_pull_request_comment(
            repository_name,
            pull_number,
            github_comment
        )

        print("\n✅ Review posted successfully!")
        print(f"Comment URL: {comment.html_url}")

    else:

        print("\nGitHub posting disabled.")
        print("Set POST_TO_GITHUB=true to post the comment.")


if __name__ == "__main__":
    main()